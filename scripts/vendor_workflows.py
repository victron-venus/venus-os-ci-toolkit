#!/usr/bin/env python3
"""Generate caller-local reusable workflows from immutable toolkit commits.

The toolkit remains the source of truth. This command copies the complete job
definition graph, while leaving pinned composite actions as ordinary steps.
It never contacts GitHub, changes runner settings, or starts a workflow.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import shutil
# Only read-only Git calls with validated arguments below.
import subprocess  # nosec B404
from pathlib import Path

from runner_selection import yaml_editor

UPSTREAM = "victron-venus/venus-os-ci-toolkit/.github/workflows/"
WORKFLOWS = ".github/workflows/"
LOCK = ".github/ci-toolkit-workflows.lock.json"
SHA = re.compile(r"[0-9a-f]{40}\Z")
NAME = re.compile(r"[A-Za-z0-9_-]+\.ya?ml\Z")


def digest(text):
    return hashlib.sha256(text.encode()).hexdigest()


def remote_ref(value):
    if not isinstance(value, str) or not value.startswith(UPSTREAM):
        return None
    name, separator, revision = value[len(UPSTREAM):].partition("@")
    if not separator or not NAME.fullmatch(name) or not SHA.fullmatch(revision):
        raise ValueError("Reusable toolkit workflows must use a full immutable commit SHA")
    return name, revision


def local_name(name, revision):
    return f"toolkit-{Path(name).stem}-{revision}.yml"


def safe_path(root, relative):
    path = root / relative
    if path.resolve() != path or not path.is_relative_to(root):
        raise ValueError("Refusing symlink or escaping workflow path")
    return path


class WorkflowBundle:
    def __init__(self, toolkit):
        self.toolkit = toolkit
        self.editor = yaml_editor()
        self.files = {}
        self.metadata = {}
        self.destinations = {}

    def dump(self, value):
        output = io.StringIO()
        self.editor.dump(value, output)
        return output.getvalue()

    def add(self, name, revision, chain=()):
        if not NAME.fullmatch(name) or not SHA.fullmatch(revision):
            raise ValueError("Invalid immutable workflow source")
        identity = (name, revision)
        if identity in chain or len(chain) >= 9:
            raise ValueError("Cyclic or excessively nested reusable workflow graph")
        destination = WORKFLOWS + local_name(name, revision)
        # Case folding also protects macOS/Windows checkouts before any writes.
        previous = self.destinations.setdefault(destination.casefold(), identity)
        if previous != identity:
            raise ValueError("Generated workflow name collision; rename the upstream source")
        if destination in self.files:
            return "./" + destination
        workflow = self.read_source(name, revision)
        self.rewrite_dependencies(workflow, name, revision, (*chain, identity))
        rendered = (
            "# Generated by scripts/vendor_workflows.py; do not edit by hand.\n"
            f"# Source: {UPSTREAM}{name}@{revision}\n" + self.dump(workflow)
        )
        self.files[destination] = rendered
        self.metadata[destination] = {
            "source_path": WORKFLOWS + name,
            "source_sha": revision,
            "sha256": digest(rendered),
        }
        return "./" + destination

    def read_source(self, name, revision):
        executable = shutil.which("git")
        if not executable:
            raise ValueError("Git is required to read the pinned source")
        # No shell, remote access or caller-controlled Git options; SHA/path are bounded.
        original = subprocess.run(  # nosec B603
            [executable, "-C", str(self.toolkit), "show", f"{revision}:{WORKFLOWS}{name}"],
            check=True, capture_output=True, text=True,
        ).stdout
        workflow = self.editor.load(original)
        events = workflow.get("on", {})
        if not isinstance(events, dict) or "workflow_call" not in events:
            raise ValueError(f"Source is not reusable: {name}")
        # Distributed definitions must never independently trigger another run.
        workflow["on"] = {"workflow_call": events["workflow_call"]}
        return workflow

    def rewrite_dependencies(self, workflow, name, revision, chain):
        for job in workflow.get("jobs", {}).values():
            reference = job.get("uses", "")
            dependency = remote_ref(reference)
            if reference.startswith("./" + WORKFLOWS):
                dependency_name = reference[len("./" + WORKFLOWS):]
                if not NAME.fullmatch(dependency_name):
                    raise ValueError("Invalid nested local workflow")
                dependency = (dependency_name, revision)
            if dependency:
                job["uses"] = self.add(*dependency, chain)
            elif reference:
                # A cross-owner job would reintroduce the runner scope ambiguity.
                raise ValueError(f"Review external nested reusable workflow in {name}")


def read_lock(repository):
    lock_path = safe_path(repository, LOCK)
    previous = json.loads(lock_path.read_text()) if lock_path.exists() else {
        "schema": 1, "files": {}, "calls": {},
    }
    if previous.get("schema") != 1:
        raise ValueError("Unsupported workflow bundle lock schema")
    for relative, metadata in previous["files"].items():
        if not relative.startswith(WORKFLOWS + "toolkit-") or not NAME.fullmatch(
            relative[len(WORKFLOWS):]
        ):
            raise ValueError("Invalid generated workflow path in lock")
        path = safe_path(repository, relative)
        if not path.is_file() or digest(path.read_text()) != metadata["sha256"]:
            raise ValueError("Generated workflow drift: " + relative)
    return previous


def rewrite_caller(bundle, original, relative, previous):
    workflow = bundle.editor.load(original)
    if not isinstance(workflow, dict) or not isinstance(workflow.get("jobs"), dict):
        raise ValueError("Invalid caller workflow: " + relative)
    changed, calls = False, {}
    for job_id, job in workflow["jobs"].items():
        reference = job.get("uses", "")
        source = reference
        if reference.startswith("./" + WORKFLOWS + "toolkit-"):
            source = previous.get("calls", {}).get(relative, {}).get(job_id, "")
            expected = remote_ref(source)
            if not expected or reference != "./" + WORKFLOWS + local_name(*expected):
                raise ValueError("Untracked generated workflow reference")
        dependency = remote_ref(source)
        if dependency:
            calls[job_id] = source
            target = bundle.add(*dependency)
            changed = changed or reference != target
            job["uses"] = target
    return bundle.dump(workflow) if changed else None, calls


def render(repository, toolkit):
    repository = Path(repository).resolve()
    previous = read_lock(repository)
    old_files = previous["files"]
    bundle = WorkflowBundle(Path(toolkit).resolve())
    files, calls = {}, {}
    directory = safe_path(repository, WORKFLOWS.rstrip("/"))
    for path in sorted(directory.glob("*")):
        relative = str(path.relative_to(repository))
        if relative in old_files or path.suffix not in {".yml", ".yaml"}:
            continue
        safe_path(repository, relative)
        rewritten, job_calls = rewrite_caller(bundle, path.read_text(), relative, previous)
        if rewritten is not None:
            files[relative] = rewritten
        if job_calls:
            calls[relative] = job_calls
    for relative in bundle.files:
        path = safe_path(repository, relative)
        if path.exists() and relative not in old_files:
            raise ValueError("Refusing to overwrite an unowned workflow")
    files.update(bundle.files)
    files[LOCK] = json.dumps({
        "schema": 1, "upstream": "victron-venus/venus-os-ci-toolkit",
        "files": bundle.metadata, "calls": calls,
    }, indent=2, sort_keys=True) + "\n"
    stale = set(old_files) - set(bundle.files)
    return files, stale


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repository", type=Path)
    parser.add_argument("--toolkit-repository", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = args.repository.resolve()
    files, stale = render(root, args.toolkit_repository)
    changed = {
        name: text for name, text in files.items()
        if not (root / name).exists() or (root / name).read_text() != text
    }
    if args.check and (changed or stale):
        parser.exit(1, "Workflow distribution requires regeneration\n")
    if not args.check:
        for name, text in changed.items():
            (root / name).write_text(text)
        for name in stale:
            (root / name).unlink()
    print(f"Verified caller-local workflows: {len(files) - 1}; changed {len(changed)}")


if __name__ == "__main__":
    main()
