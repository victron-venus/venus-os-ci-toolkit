"""Opt a known generated CI graph into reviewed documentation-only routing.

Only selected YAML scalars/conditions change. No release runtime, action pin,
trigger, runner, deadline or publication step is regenerated. Unknown graphs
fail before the caller receives any files to write.
"""
from __future__ import annotations

import copy
import json
from pathlib import Path

import yaml
from release_receipt_migration import read_local

MARKER = "# Generated by venus-os-ci-toolkit/scripts/install_release.py; edit .release-policy.json.\n"
QUALITY = ".github/workflows/quality-gate.yml"
RELEASE = ".github/workflows/release-pipeline.yml"
CLASSIFIER = "scripts/change_scope.py"
SCOPE_FIELDS = ("DOCUMENTATION_PATHS", "REQUIRED_PATHS", "FORCE_FULL")


def normalized(value):
    """Compare YAML scalar values as GitHub expressions, without boolean coercion."""
    return yaml.load(yaml.safe_dump(value), Loader=yaml.BaseLoader)


class ScalarEditor:
    """Edit admitted block-mapping values, preserving every unrelated source byte."""

    def __init__(self, source, loader):
        if not source.startswith(MARKER):
            raise ValueError("Change-scope migration requires the generated marker")
        self.source = source
        yaml.load(source, Loader=loader)
        self.data = yaml.load(source, Loader=yaml.BaseLoader)
        self.tree = yaml.compose(source, Loader=yaml.BaseLoader)
        self.node_counts = {}
        self.count_nodes(self.tree, set(), set())
        self.expected = copy.deepcopy(self.data)
        self.edits = []
        if not isinstance(self.data, dict) or self.data.get("defaults"):
            raise ValueError("Unknown workflow defaults or document shape")

    def count_nodes(self, node, active, seen):
        """Permit unrelated anchors, but reject cyclic or edited aliased subtrees."""
        identity = id(node)
        self.node_counts[identity] = self.node_counts.get(identity, 0) + 1
        if identity in active:
            raise ValueError("Cyclic workflow YAML")
        if identity in seen:
            return
        active.add(identity)
        seen.add(identity)
        if isinstance(node, yaml.MappingNode):
            children = [child for pair in node.value for child in pair]
        elif isinstance(node, yaml.SequenceNode):
            children = node.value
        else:
            children = []
        for child in children:
            self.count_nodes(child, active, seen)
        active.remove(identity)

    def node(self, path):
        node = self.tree
        for part in path:
            if self.node_counts[id(node)] != 1:
                raise ValueError("Edited YAML subtree is aliased")
            if isinstance(part, int) and isinstance(node, yaml.SequenceNode):
                node = node.value[part]
            elif isinstance(node, yaml.MappingNode) and not node.flow_style:
                matches = [value for key, value in node.value if key.value == part]
                if len(matches) != 1:
                    raise ValueError("Missing or ambiguous YAML path: " + str(path))
                node = matches[0]
            else:
                raise ValueError("Expected block mapping: " + str(path))
        if self.node_counts[id(node)] != 1:
            raise ValueError("Edited YAML node is aliased")
        return node

    def expected_parent(self, path):
        value = self.expected
        for part in path[:-1]:
            value = value[part]
        return value

    def set(self, path, value):
        node = self.node(path)
        if node.id != "scalar":
            raise ValueError("Expected scalar: " + str(path))
        if node.value == value:
            return
        if "\n" in value:
            parent = self.node(path[:-1])
            key = next(key for key, candidate in parent.value if candidate is node)
            indent = " " * (key.start_mark.column + 2)
            replacement = "|\n" + "".join(indent + line + "\n" for line in value.splitlines())
        else:
            replacement = json.dumps(value)
        self.edits.append((node.start_mark.index, node.end_mark.index, replacement))
        self.expected_parent(path)[path[-1]] = value

    def condition(self, job, value):
        path = ("jobs", job, "if")
        current = self.data["jobs"][job]
        if "if" in current:
            if value is not None:
                self.set(path, value)
                return
            mapping = self.node(path[:-1])
            key, node = next((key, node) for key, node in mapping.value if key.value == "if")
            start = self.source.rfind("\n", 0, key.start_mark.index) + 1
            if self.source[start:key.start_mark.index].strip():
                raise ValueError("Condition must occupy its own block-mapping line")
            end = node.end_mark.index
            if not (node.style in {"|", ">"} and node.end_mark.column == 0):
                next_line = self.source.find("\n", end)
                if next_line == -1:
                    next_line = len(self.source)
                tail = self.source[end:next_line].strip()
                if tail and not tail.startswith("#"):
                    raise ValueError("Unknown condition suffix")
                end = min(next_line + 1, len(self.source))
            self.edits.append((start, end, ""))
            del self.expected_parent(path)["if"]
        elif value is not None:
            mapping = self.node(path[:-1])
            first_key = mapping.value[0][0]
            start = self.source.rfind("\n", 0, first_key.start_mark.index) + 1
            if self.source[start:first_key.start_mark.index].strip():
                raise ValueError("Job must use a block mapping")
            line = " " * first_key.start_mark.column + "if: " + json.dumps(value) + "\n"
            self.edits.append((start, start, line))
            self.expected_parent(path)["if"] = value

    def finish(self, loader):
        end = len(self.source) + 1
        result = self.source
        for start, stop, replacement in sorted(self.edits, reverse=True):
            if stop > end:
                raise ValueError("Overlapping scalar edits")
            result = result[:start] + replacement + result[stop:]
            end = start
        yaml.load(result, Loader=loader)
        if yaml.load(result, Loader=yaml.BaseLoader) != self.expected:
            raise ValueError("Migration changed an unselected workflow value")
        return result


def scope_step(workflow, canonical):
    """Admit the complete known classifier job, except immutable runner/action pins."""
    job = workflow.get("jobs", {}).get("scope")
    if not job or not isinstance(job, dict):
        raise ValueError("Legacy or custom gate has no shared scope job; review it separately")
    allowed = {"name", "runs-on", "timeout-minutes", "outputs", "steps", "if"}
    if set(job) - allowed:
        raise ValueError("Unknown scope-job customization")
    for name in ("name", "timeout-minutes", "outputs"):
        if job.get(name) != canonical[name]:
            raise ValueError("Unknown classifier " + name)
    steps = job.get("steps", [])
    offset = 0
    if len(steps) == 3:
        hardening = steps[0]
        if not hardening.get("uses", "").startswith("step-security/harden-runner@"):
            raise ValueError("Unknown classifier preflight step")
        if set(hardening) - {"name", "uses", "with"}:
            raise ValueError("Unknown classifier preflight settings")
        offset = 1
    if len(steps) != offset + 2:
        raise ValueError("Unknown classifier step inventory")
    checkout, decision = steps[offset:]
    if (set(checkout) != {"uses", "with"}
            or not checkout["uses"].startswith("actions/checkout@")
            or checkout["with"] != canonical["steps"][0]["with"]):
        raise ValueError("Classifier must use a full-history credential-free checkout")
    expected = canonical["steps"][1]
    for key in ("id", "name", "run"):
        if decision.get(key) != expected[key]:
            raise ValueError("Unknown classifier command or identity")
    if set(decision) != set(expected) or set(decision.get("env", {})) != set(SCOPE_FIELDS):
        raise ValueError("Unknown classifier inputs")
    if decision["env"]["FORCE_FULL"] not in {"true", "false", "${{ inputs.force-full && 'true' || 'false' }}"}:
        raise ValueError("Unknown classifier force policy")
    return offset + 1, decision["env"]


def old_policy(policy, jobs, env, generator):
    """Infer only the previous declarative scope values, never security requirements."""
    old = copy.deepcopy(policy)
    private = policy.get("visibility") == "private"
    success = "${{ (success()) && (github.event_name != 'schedule' || vars.NIGHTLY_CHECKS_ENABLED == 'true') }}"
    always = []
    for index, filename in enumerate(policy["validation_workflows"]):
        condition = jobs[f"check-{index}"].get("if")
        if condition == (success if private else None):
            always.append(filename)
    old["change_scope"] = {
        "documentation_paths": json.loads(env["DOCUMENTATION_PATHS"]),
        "required_paths": json.loads(env["REQUIRED_PATHS"]),
        "always_validate_workflows": always,
    }
    generator.scope_policy(old)
    return old


def compare_graph(actual, expected, *, release=False):
    """Reject unknown jobs, dependencies, predicates and execution overrides."""
    jobs = actual.get("jobs", {})
    wanted = expected["jobs"]
    if set(jobs) != set(wanted):
        raise ValueError("Unknown validation/publication job inventory")
    for name, job in jobs.items():
        if job.get("defaults") or job.get("continue-on-error"):
            raise ValueError("Unknown job execution override: " + name)
        for field in ("needs", "if"):
            legacy_checks = (release and name == "checks" and field == "if"
                             and job.get(field) == "${{ needs.prepare.outputs.build == 'true' || needs.prepare.outputs.status == 'version-required' }}")
            if job.get(field) != wanted[name].get(field) and not legacy_checks:
                raise ValueError("Unknown dependency or condition: " + name + "/" + field)
        if ((name.startswith("check-") or release and name == "checks")
                and job.get("uses") != wanted[name].get("uses")):
            raise ValueError("Unknown validator target: " + name)
    if release:
        checks = jobs["checks"]
        if checks.get("with", {}).get("force-full") != "true":
            raise ValueError("Release qualification must force full validation")


def migrate_quality(editor, policy, generator):
    desired = normalized(generator.quality(policy))
    index, env = scope_step(editor.data, normalized(generator.scope_job(policy, force_input=True)))
    previous = old_policy(policy, editor.data["jobs"], env, generator)
    expected = normalized(generator.quality(previous))
    compare_graph(editor.data, expected)
    jobs = editor.data["jobs"]
    gate = jobs["gate"]
    if set(gate) - {"name", "needs", "if", "runs-on", "timeout-minutes", "steps"}:
        raise ValueError("Unknown gate-job execution configuration")
    old_steps, new_steps = gate.get("steps", []), expected["jobs"]["gate"]["steps"]
    gate_index = len(old_steps) - 1
    if gate_index not in {0, 1} or old_steps[gate_index] != new_steps[-1]:
        raise ValueError("Unknown gate proof command")
    if gate_index == 1 and not old_steps[0].get("uses", "").startswith("step-security/harden-runner@"):
        raise ValueError("Unknown gate preflight")
    for key in SCOPE_FIELDS:
        editor.set(("jobs", "scope", "steps", index, "env", key), desired["jobs"]["scope"]["steps"][-1]["env"][key])
    for name, job in desired["jobs"].items():
        if name != "scope":
            editor.condition(name, job.get("if"))
    editor.set(("jobs", "gate", "steps", gate_index, "run"), desired["jobs"]["gate"]["steps"][-1]["run"])


def migrate_release(editor, policy, generator):
    desired = normalized(generator.release(policy))
    index, _ = scope_step(editor.data, normalized(generator.scope_job(policy)))
    compare_graph(editor.data, desired, release=True)
    for key in SCOPE_FIELDS:
        editor.set(("jobs", "scope", "steps", index, "env", key), desired["jobs"]["scope"]["steps"][-1]["env"][key])


def render(directory: Path, generator=None) -> dict[str, str]:
    """Return only admitted scope edits; policy/security selection belongs to review."""
    if generator is None:
        import install_release as generator  # pylint: disable=import-outside-toplevel
    policy = json.loads(read_local(directory, ".release-policy.json"))
    if (not isinstance(policy, dict) or "change_scope" not in policy
            or policy.get("mode", "release") not in {"release", "validation-only"}
            or policy.get("ci_execution", "github") != "github"):
        raise ValueError("Declare a reviewed change_scope policy for hosted CI first")
    generator.scope_policy(policy)
    names = [QUALITY]
    if policy.get("mode", "release") == "release":
        names.append(RELEASE)
    canonical = generator.consumer_python((generator.ROOT / CLASSIFIER).read_text())
    existing = read_local(directory, CLASSIFIER)
    if existing != canonical:
        raise ValueError("Unknown classifier revision; review and update it separately")
    changes = {}
    for name in names:
        source = read_local(directory, name)
        editor = ScalarEditor(source, generator.WorkflowLoader)
        if name == QUALITY:
            migrate_quality(editor, policy, generator)
        else:
            migrate_release(editor, policy, generator)
        result = editor.finish(generator.WorkflowLoader)
        if result != source:
            changes[name] = result
    return changes
