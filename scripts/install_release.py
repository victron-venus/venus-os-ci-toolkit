def validate_local_policy(directory: Path, policy: dict) -> None:
    """Keep local validation independent of unavailable hosted workflow adapters."""
    if policy.get("mode") != "validation-only" or policy.get("validation_workflows"):
        raise ValueError(
            "Local CI requires validation-only mode and no hosted validators"
        )
    if (directory / ".github/workflows/quality-gate.yml").exists():
        raise ValueError(
            "Archive the unavailable hosted quality-gate.yml before rendering local CI"
        )
    commands = policy.get("local_checks")
    if (
        not isinstance(commands, list)
        or not commands
        or any(
            not isinstance(command, str) or not command.strip() for command in commands
        )
    ):
        raise ValueError("Local CI needs a nonempty list of reviewed local_checks")
    if not (directory / "scripts/ci.sh").is_file():
        raise ValueError("Local CI requires scripts/ci.sh")
    validate_local_workflows(directory)


def validate_local_workflows(directory: Path) -> None:
    """Allow only explicit manual jobs on an existing self-hosted runner."""
    for path in (directory / ".github/workflows").glob("*.y*ml"):
        workflow = yaml.load(path.read_text(), Loader=yaml.BaseLoader)
        if set(workflow.get("on", {})) != {"workflow_dispatch"}:
            raise ValueError(f"Archive unavailable automatic workflow: {path}")
        jobs = workflow.get("jobs", {})
        if not jobs:
            raise ValueError(f"Local workflow has no jobs: {path}")
        for job in jobs.values():
            runner = job.get("runs-on", [])
            labels = [runner] if isinstance(runner, str) else runner
            if "uses" in job or "self-hosted" not in labels:
                raise ValueError(f"Archive unavailable hosted workflow: {path}")


def validate_workflow_adapters(directory: Path, policy: dict) -> None:
    """Check callable validators and permission caps throughout their local graph."""
    validate_local_calls(directory, quality(policy))
    if policy.get("mode", "release") == "release":
        validate_build_secrets(directory, policy)
    if policy.get("versioning"):
        path = directory / ".github/workflows/release-build.yml"
        declaration = yaml.load(path.read_text(), Loader=yaml.BaseLoader)
        for key in ("on", "workflow_call", "inputs", "release_plan_artifact"):
            declaration = (
                declaration.get(key) if isinstance(declaration, dict) else None
            )
        if (
            not isinstance(declaration, dict)
            or declaration.get("type") != "string"
            or declaration.get("required") != "true"
        ):
            raise ValueError(
                "Versioned release-build.yml must declare release_plan_artifact "
                "as a required string workflow_call input"
            )


def validate_build_secrets(directory: Path, policy: dict) -> None:
    """Reject undeclared, unused or implicit secrets before rendering a caller."""
    path = directory / ".github/workflows/release-build.yml"
    text = path.read_text()
    workflow = yaml.load(text, Loader=yaml.BaseLoader)
    declared = workflow.get("on", {}).get("workflow_call", {}).get("secrets", {})
    used = set(re.findall(r"secrets\.([A-Za-z_][A-Za-z0-9_]*)", text)) - {
        "GITHUB_TOKEN"
    }
    forwarded = set(build_secrets(policy))
    if (
        not isinstance(declared, dict)
        or set(declared) != forwarded
        or used != forwarded
    ):
        raise ValueError(
            "build_secrets must exactly match release-build.yml declarations and usage"
        )
    if re.search(r"secrets\s*\[", text) or any(
        job.get("secrets") == "inherit" for job in workflow.get("jobs", {}).values()
    ):
        raise ValueError("Build workflows must use explicit named secrets")


def permission_level(permissions: dict | str, scope: str) -> str:
    """Resolve one declared scope, including the workflow wildcard forms."""
    if isinstance(permissions, dict):
        return permissions.get(scope, "none")
    if permissions in {"read-all", "write-all"}:
        return permissions.removesuffix("-all")
    raise ValueError(f"Unsupported permissions declaration: {permissions!r}")


def validate_permission_cap(requested: dict | str, allowed: dict | str, label: str):
    """Reject static permission elevation even when a job's condition is false."""
    scopes = {"*"}
    for declaration in (requested, allowed):
        if isinstance(declaration, dict):
            scopes.update(declaration)
    levels = {"none": 0, "read": 1, "write": 2}
    for scope in sorted(scopes):
        need = permission_level(requested, scope)
        cap = permission_level(allowed, scope)
        if levels[need] > levels[cap]:
            raise ValueError(
                f"{label}: requests {scope}: {need}, but caller allows {cap}"
            )


def validate_codeql_pins(workflow: dict) -> None:
    """Keep the shared CodeQL configuration version consistent within each job."""
    for name, job in workflow.get("jobs", {}).items():
        pins = set()
        for step in job.get("steps", []):
            reference = step.get("uses", "")
            if not re.match(
                r"github/codeql-action/(init|autobuild|analyze)@", reference
            ):
                continue
            pin = reference.rsplit("@", 1)[1]
            if not re.fullmatch(r"[0-9a-f]{40}", pin):
                raise ValueError(
                    f"CodeQL job {name}: every action needs a full commit SHA"
                )
            pins.add(pin)
        if len(pins) > 1:
            raise ValueError(
                f"CodeQL job {name}: init, autobuild and analyze must use the same SHA"
            )


def validate_local_calls(directory, workflow, allowed=None, chain=()):
    """Validate local calls without fetching or trusting mutable remote workflows."""
    validate_codeql_pins(workflow)
    defaults = workflow.get("permissions", allowed or {})
    for name, job in workflow.get("jobs", {}).items():
        permissions = job.get("permissions", defaults)
        label = " -> ".join((*chain, name))
        if allowed is not None:
            validate_permission_cap(permissions, allowed, label)
        reference = job.get("uses", "")
        if not reference.startswith("./"):
            continue
        if not re.fullmatch(r"\./\.github/workflows/[A-Za-z0-9_-]+\.ya?ml", reference):
            raise ValueError(f"Invalid local workflow reference: {reference}")
        if reference in chain:
            raise ValueError(f"Recursive local workflow call: {label} -> {reference}")
        path = directory / reference
        called = yaml.load(path.read_text(), Loader=yaml.BaseLoader)
        if "workflow_call" not in called.get("on", {}):
            raise ValueError(f"{path}: needs workflow_call")
        validate_local_calls(directory, called, permissions, (*chain, reference))


