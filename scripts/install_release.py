def main():
    """Render files or fail a read-only check when any generated file has drifted."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        files = render(args.directory)
        drift = []
        for relative, content in files.items():
            path = args.directory / relative
            if args.check:
                if not path.is_file() or path.read_text() != content:
                    drift.append(relative)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
                if path.suffix == ".py":
                    path.chmod(0o755)
        if drift:
            raise ValueError("Generated files drifted: " + ", ".join(drift))
        print(
            f"{'Verified' if args.check else 'Rendered'} {len(files)} files in {args.directory}"
        )
    except (OSError, KeyError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


