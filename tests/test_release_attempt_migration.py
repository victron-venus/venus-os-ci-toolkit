"""Narrow artifact migration preserves consumer-owned release behavior."""

import copy
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
import install_release as installer
import release_attempt_migration as migration
from release_attempt_workflow import SUFFIX

REF = "a" * 40
HEADER = "# Generated by venus-os-ci-toolkit/scripts/install_release.py; edit .release-policy.json.\n"
PRODUCER = {"jobs": {"campaign": {"steps": [{
    "uses": "actions/upload-artifact@unchanged",
    "with": {"name": "release-assets-fuzz" + SUFFIX},
}]}}}


class ReleaseAttemptMigrationTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        (self.root / ".github/workflows").mkdir(parents=True)
        self.policy = {"repository": "owner/project", "mode": "release", "visibility": "public",
                       "versioning": {"schema": 1}, "fuzzing": {"toolkit_ref": REF}}
        plan = "${{ needs.prepare.outputs.plan_artifact }}"
        publisher = {"steps": [
            {"uses": "actions/download-artifact@old-pin", "with": {"name": plan}},
            {"uses": "actions/download-artifact@old-pin", "with": {
                "pattern": "release-assets*", "path": ".release-download", "merge-multiple": False}},
            {"run": "python3 scripts/release.py collect .release-download .release-assets"},
            {"run": "python3 scripts/release_versioned.py publish --assets .release-assets"},
        ]}
        self.pipeline = {"on": {"workflow_dispatch": {}}, "jobs": {
            "prepare": {"outputs": {"plan_artifact": "${{ steps.metadata.outputs.plan_artifact }}"}},
            "build": {"uses": migration.BUILD, "with": {"release_plan_artifact": plan}},
            "fuzz": {"uses": f"{migration.TOOLKIT}/.github/workflows/fuzz.yml@{REF}",
                     "with": {"toolkit-ref": REF, "release-plan-artifact": plan}},
            "candidate": copy.deepcopy(publisher), "final": copy.deepcopy(publisher),
            "custom": {"runs-on": "unchanged-runner", "steps": [{"run": "echo custom-validation"}]},
        }}
        self.build = {"on": {"workflow_call": {}}, "jobs": {"package": {"steps": [
            {"run": "echo package > package.tar"},
            {"uses": "actions/download-artifact@old-pin", "with": {
                "name": "${{ inputs.release_plan_artifact }}"}},
            {"uses": "actions/download-artifact@old-pin", "with": {
                "artifact-ids": "123", "run-id": "42"}},
            {"uses": "actions/upload-artifact@old-pin", "with": {
                "name": "release-assets", "path": "package.tar"}},
        ]}}}
        self.write()
        (self.root / "runtime.py").write_text("# consumer runtime remains unchanged\n")

    def write(self):
        (self.root / ".release-policy.json").write_text(json.dumps(self.policy))
        (self.root / migration.PIPELINE).write_text(installer.dump(self.pipeline))
        (self.root / migration.BUILD.removeprefix("./")).write_text(installer.dump(self.build))

    def render(self):
        with patch.object(migration, "pinned_fuzz_workflow", return_value=PRODUCER):
            return installer.render_release_attempts(self.root)

    def snapshot(self):
        return {p.relative_to(self.root).as_posix(): p.read_bytes()
                for p in self.root.rglob("*") if p.is_file()}

    def rejected_without_writes(self, message):
        before = self.snapshot()
        with self.assertRaisesRegex(ValueError, message):
            self.render()
        self.assertEqual(self.snapshot(), before)

    def test_changes_only_artifact_edges_and_is_idempotent(self):
        before = self.snapshot()
        files = self.render()
        self.assertEqual(set(files), {migration.PIPELINE, migration.BUILD.removeprefix("./")})
        self.assertEqual(self.snapshot(), before, "rendering must not write files")
        for name, source in files.items():
            changed = installer.yaml.load(source, Loader=installer.WorkflowLoader)
            original = installer.yaml.load(before[name], Loader=installer.WorkflowLoader)
            for job in changed["jobs"].values():
                for step in job.get("steps", []):
                    for key in ("name", "pattern"):
                        value = step.get("with", {}).get(key)
                        if isinstance(value, str):
                            step["with"][key] = value.removesuffix(SUFFIX)
            self.assertEqual(changed, original)
            (self.root / name).write_text(source)
        self.assertEqual(self.render(), {})
        self.assertEqual((self.root / ".release-policy.json").read_bytes(), before[".release-policy.json"])
        self.assertEqual((self.root / "runtime.py").read_bytes(), before["runtime.py"])

    def test_check_mode_detects_drift_without_writing(self):
        before = self.snapshot()
        with patch.object(migration, "pinned_fuzz_workflow", return_value=PRODUCER), \
                patch.object(sys, "argv", ["install_release.py", str(self.root), "--release-attempts-only", "--check"]):
            self.assertEqual(installer.main(), 1)
        self.assertEqual(self.snapshot(), before)

    def test_unsupported_policies_fail_before_any_write(self):
        for change in ({"versioning": {}}, {"mode": "validation-only"},
                       {"visibility": "private"}, {"ci_execution": "local"}, {"artifact_pattern": ""}):
            with self.subTest(change=change):
                original = self.policy.copy()
                self.policy.update(change)
                self.write()
                self.rejected_without_writes("requires")
                self.policy = original

    def test_policy_does_not_upgrade_a_legacy_saved_workflow(self):
        del self.pipeline["jobs"]["build"]["with"]["release_plan_artifact"]
        self.write()
        self.rejected_without_writes("version-plan")

    def test_drifted_collector_pattern_is_not_partially_migrated(self):
        self.policy["artifact_pattern"] = "packages*"
        self.write()
        self.rejected_without_writes("collector does not match")

    def test_custom_matching_package_pattern_is_supported(self):
        self.policy.pop("fuzzing")
        self.pipeline["jobs"].pop("fuzz")
        self.policy["artifact_pattern"] = "packages*"
        for name in ("candidate", "final"):
            self.pipeline["jobs"][name]["steps"][1]["with"]["pattern"] = "packages*"
        self.build["jobs"]["package"]["steps"][-1]["with"]["name"] = "packages-linux"
        self.write()
        result = self.render()
        self.assertIn("packages*" + SUFFIX, result[migration.PIPELINE])
        self.assertIn("packages-linux" + SUFFIX, result[migration.BUILD.removeprefix("./")])

    def test_unmanaged_pipeline_is_rejected(self):
        path = self.root / migration.PIPELINE
        path.write_text(path.read_text().removeprefix(HEADER))
        self.rejected_without_writes("generated")

    def test_anchors_and_external_consumers_are_not_rewritten(self):
        path = self.root / migration.BUILD.removeprefix("./")
        path.write_text("on: {workflow_call: {}}\njobs:\n  package:\n    steps:\n"
                        "      - uses: actions/upload-artifact@pin\n"
                        "        with: &shared {name: release-assets, path: package.tar}\n"
                        "copy: *shared\n")
        self.rejected_without_writes("anchors")
        self.write()
        (self.root / ".github/workflows/ordinary.yml").write_text(installer.dump({
            "jobs": {"check": {"uses": migration.BUILD}}}))
        self.rejected_without_writes("outside the release graph")

    def test_remote_build_producer_is_not_silently_ignored(self):
        self.build["jobs"]["remote"] = {"uses": "owner/remote/.github/workflows/build.yml@" + REF}
        self.write()
        self.rejected_without_writes("remote build")

    def test_independent_adapter_triggers_are_not_silently_migrated(self):
        self.build["on"]["push"] = {}
        self.write()
        self.rejected_without_writes("only workflow_call")

    def test_string_merge_multiple_cannot_overwrite_duplicate_assets(self):
        # An extra download outside the package collector must not merge inputs either.
        for enabled in (True, "true", "TRUE", "True"):
            with self.subTest(enabled=enabled):
                original = copy.deepcopy(self.pipeline)
                self.pipeline["jobs"]["custom"]["steps"].append({
                    "uses": "actions/download-artifact@old-pin",
                    "with": {"pattern": "extra*", "merge-multiple": enabled},
                })
                self.write()
                self.rejected_without_writes("separate artifact directories")
                self.pipeline = original

    def test_unscoped_shared_producer_requires_a_separate_upgrade(self):
        old = copy.deepcopy(PRODUCER)
        old["jobs"]["campaign"]["steps"][0]["with"]["name"] = "release-assets-fuzz"
        with patch.object(migration, "pinned_fuzz_workflow", return_value=old):
            with self.assertRaisesRegex(ValueError, "coordinated producer upgrade"):
                installer.render_release_attempts(self.root)

    def test_shared_caller_mismatch_and_candidate_mode_are_rejected(self):
        for key, value in (("toolkit-ref", "b" * 40), ("evidence-mode", "candidate")):
            with self.subTest(key=key):
                original = copy.deepcopy(self.pipeline)
                self.pipeline["jobs"]["fuzz"]["with"][key] = value
                self.write()
                self.rejected_without_writes("source-pinned release-mode")
                self.pipeline = original

    def test_shared_blob_lookup_never_fetches_or_uses_replacements(self):
        completed = subprocess.CompletedProcess([], 0, stdout=json.dumps(PRODUCER))
        hostile = {"GIT_DIR": "/wrong/repo", "GIT_WORK_TREE": "/wrong/tree",
                   "GIT_OBJECT_DIRECTORY": "/wrong/objects", "GIT_CONFIG_COUNT": "1",
                   "GIT_CONFIG_KEY_0": "core.repositoryformatversion", "GIT_CONFIG_VALUE_0": "999",
                   "UNRELATED_SECRET": "must-not-be-forwarded"}
        with patch.dict(os.environ, hostile), \
                patch.object(migration.subprocess, "run", return_value=completed) as run:
            self.assertEqual(migration.pinned_fuzz_workflow(self.root, REF, installer.WorkflowLoader), PRODUCER)
        argv = run.call_args.args[0]
        self.assertIn("--no-replace-objects", argv)
        self.assertEqual(argv[-1], REF + ":.github/workflows/fuzz.yml")
        self.assertEqual(run.call_args.kwargs["env"]["GIT_NO_LAZY_FETCH"], "1")
        self.assertEqual(run.call_args.kwargs["env"]["GIT_NO_REPLACE_OBJECTS"], "1")
        self.assertEqual(run.call_args.kwargs["env"]["GIT_CONFIG_GLOBAL"], os.devnull)
        self.assertEqual(run.call_args.kwargs["env"]["GIT_CONFIG_NOSYSTEM"], "1")
        self.assertTrue(set(hostile).isdisjoint(run.call_args.kwargs["env"]))
        with patch.object(migration.subprocess, "run", return_value=subprocess.CompletedProcess([], 128, stdout="")):
            with self.assertRaisesRegex(ValueError, "containing producer revision"):
                migration.pinned_fuzz_workflow(self.root, REF, installer.WorkflowLoader)


if __name__ == "__main__":
    unittest.main()
